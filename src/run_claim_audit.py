"""
Run Stage 1 of the claim-auditing process for Airbnb review summaries.

This script evaluates whether the summaries generated by System A
(conventional summarization) and System B (evidence-grounded
summarization) are supported by the reviews each system received.

The evaluation is blind to the experimental ground truth:
- The judge receives the generated summary and the corresponding
  scenario's model-visible reviews.
- It does not receive synthetic-review labels, attack metadata,
  human annotations, or the ground-truth benchmark.

This distinction is important because a summary can accurately
reflect a manipulated collection of reviews while still being
misleading about the property's genuine review history.

Stage 1 therefore measures input faithfulness rather than
ground-truth accuracy.

The script:
1. Loads the experimental scenarios.
2. Finds saved summarization results.
3. Selects scenarios eligible for auditing.
4. Checks whether previous audits can be reused.
5. Evaluates System A and System B using the OpenAI judge.
6. Saves each system's audit and associated API metadata.
7. Marks a scenario's audit complete after both systems finish.

Intermediate results are saved so that successfully completed
system audits can be reused if execution is interrupted.

Running this script makes OpenAI API requests for systems that
do not already have saved audit results.
"""

from __future__ import annotations

# Provides command-line argument parsing.
#
# This allows the user to select specific scenarios and control
# whether existing audit files should be overwritten.
import argparse

# Import shared utilities used throughout the experiment.
from experiment_common import (
    ROOT,  # Absolute path to the project root.
    load_scenarios,  # Load and validate scenario metadata and reviews.
    visible_reviews,  # Prepare reviews in the model-visible format.
    read_json,  # Read previously saved JSON results.
    write_json,  # Save JSON results and create parent folders.
    prompt,  # Load a prompt template from the prompts directory.
    canonical,  # Serialize data into a consistent JSON string.
)

# Import the OpenAI API adapter and configured judge model.
#
# openai_json() sends a request and returns:
# - Parsed JSON response.
# - Raw response text.
# - API request ID.
# - Token usage metadata.
#
# OPENAI_JUDGE_MODEL identifies the model used for evaluation.
from model_clients import openai_json, OPENAI_JUDGE_MODEL


def main():
    """
    Audit saved summaries against their corresponding scenario inputs.

    Each scenario is evaluated separately for System A and System B.

    The function skips incomplete summarization results, supports
    filtering by scenario ID, and avoids repeating completed audits
    unless the overwrite option is supplied.

    Audit outputs are saved under results/claim_audits/.
    """

    # Set up the command-line interface.
    #
    # argparse allows the script to accept optional parameters
    # when executed from a terminal.
    ap = argparse.ArgumentParser()

    # Allow one or more scenario IDs to be specified.
    #
    # action="append" means this argument can be supplied multiple
    # times, with each occurrence added to a list.
    #
    # Example:
    # python src/audit_claims.py --scenario-id scenario_001
    #
    # To evaluate multiple scenarios:
    # python src/audit_claims.py --scenario-id scenario_001 \
    #     --scenario-id scenario_002
    #
    # The scenario IDs above are illustrative, not necessarily
    # IDs used in the actual experiment.
    #
    # If the argument is omitted, all eligible scenarios are
    # considered for auditing.
    ap.add_argument("--scenario-id", action="append")

    # Add an optional flag for overwriting existing audit files.
    #
    # action="store_true" means the value is False by default
    # and becomes True when --overwrite is provided.
    #
    # Without this flag, existing completed audits are reused.
    ap.add_argument("--overwrite", action="store_true")

    # Parse the command-line arguments.
    args = ap.parse_args()

    # Load the scenario manifest and review collections.
    #
    # load_scenarios() validates the scenario definitions and
    # returns:
    # - manifest: Metadata describing each experimental condition.
    # - groups: Dictionary mapping scenario IDs to their reviews.
    #
    # Only groups is needed here, so the manifest is assigned to _.
    #
    # The manifest may contain attack metadata, but it is not
    # passed to the judge.
    _, groups = load_scenarios()

    # Locate the directory containing the saved summaries.
    #
    # Each JSON file is expected to contain the results of a
    # summarization scenario, including the outputs of both systems.
    folder = ROOT / "results/summaries"

    # Process every JSON file in the summaries directory.
    #
    # glob("*.json") finds JSON files directly inside this folder.
    # sorted() gives the files a consistent processing order.
    #
    # This makes progress messages easier to follow and ensures
    # that scenarios are considered in a predictable order.
    for path in sorted(folder.glob("*.json")):

        # Load the saved summarization result.
        item = read_json(path)

        # Retrieve the scenario ID associated with this result.
        #
        # This ID connects the saved summaries to the corresponding
        # review collection in the scenario input files.
        sid = item["scenario_id"]

        # Apply the optional scenario filter.
        #
        # If specific scenario IDs were supplied, skip any
        # result whose ID is not in that list.
        #
        # If no IDs were supplied, this condition is False
        # and all scenarios remain eligible.
        if args.scenario_id and sid not in args.scenario_id:
            continue

        # Only audit summarization runs marked as complete.
        #
        # Incomplete results may be missing one system's summary
        # or may contain intermediate outputs that should not
        # be treated as final.
        #
        # Skipping them prevents the judge from evaluating
        # partially completed experiments.
        if item.get("status") != "complete":
            continue

        # Reconstruct the exact review collection presented
        # to the summarization systems for this scenario.
        #
        # visible_reviews() sorts the reviews, replaces their
        # original IDs with neutral sequential IDs, and retains
        # the dates and text.
        #
        # This keeps the judge's review input consistent with
        # the model-visible representation used for summarization.
        #
        # The judge is NOT given:
        # - Whether each review is genuine or synthetic.
        # - Which attack variant or intensity was used.
        # - Human annotations of important concerns.
        # - The ground-truth benchmark.
        #
        # This is what makes the first evaluation stage blind
        # to the experimental manipulation.
        reviews = visible_reviews(groups[sid])

        # Construct the output path for this scenario's claim audit.
        #
        # Each scenario receives its own JSON file so results
        # can be inspected and resumed independently.
        out = ROOT / "results/claim_audits" / f"{sid}.json"

        # Check whether a previous audit exists.
        #
        # If the file exists and --overwrite was NOT supplied,
        # load it so previously completed system evaluations
        # can be reused.
        #
        # If --overwrite was supplied, existing is set to None,
        # causing the audit to be rebuilt from the beginning.
        existing = read_json(out) if out.exists() and not args.overwrite else None

        # Confirm that an existing audit corresponds to the
        # same summarization source files.
        #
        # source_hashes records fingerprints associated with
        # the summarization run.
        #
        # If these hashes differ, the source inputs or other
        # tracked materials may have changed since the audit
        # was originally created.
        #
        # Reusing an old audit under those circumstances could
        # incorrectly associate judgments with newer results.
        #
        # The script therefore stops and requires an explicit
        # overwrite instead of silently mixing versions.
        if existing and existing.get("summary_source_hash") != item["source_hashes"]:
            raise RuntimeError(
                f"{sid}: source hashes changed; "
                "archive old audit and use --overwrite"
            )

        # Confirm that an existing audit was produced with
        # the same configured judge model.
        #
        # Different models may interpret the same claims
        # differently, so mixing judgments from different
        # judge models could undermine comparability.
        #
        # If the model identifier has changed, the script
        # requires the audit to be regenerated explicitly.
        if existing and existing.get("judge_model") != OPENAI_JUDGE_MODEL:
            raise RuntimeError(
                f"{sid}: judge model changed; " "archive old audit and use --overwrite"
            )

        # Skip a scenario if its existing audit is already
        # marked complete.
        #
        # This avoids unnecessary repeat API requests,
        # reducing runtime and API costs.
        #
        # Supplying --overwrite bypasses this check because
        # existing will have been set to None.
        if existing and existing.get("status") == "complete":
            print("Skipping completed audit:", sid)
            continue

        # Resume an existing incomplete audit, or initialize
        # a new audit record.
        #
        # An incomplete audit may already contain a judgment
        # for one of the systems. Reusing it allows the script
        # to continue without repeating that API request.
        #
        # For a new audit, the record stores:
        # - The scenario ID.
        # - The configured judge model.
        # - The source hashes from the summarization run.
        # - The evaluation stage.
        # - A dictionary for system-specific results.
        # - A pending completion status.
        result = existing or {
            "scenario_id": sid,
            "judge_model": OPENAI_JUDGE_MODEL,
            "summary_source_hash": item["source_hashes"],
            "stage": "blind_input_faithfulness",
            "systems": {},
            "status": "pending",
        }

        # Evaluate both summarization systems.
        #
        # System A is the conventional summarizer.
        # System B is the evidence-grounded summarizer.
        #
        # Both are evaluated against the same scenario's
        # model-visible review collection.
        #
        # This provides a consistent basis for comparing
        # how faithfully their summaries reflect the inputs.
        for key in ("system_a", "system_b"):

            # Skip a system if an audit result is already saved.
            #
            # This is particularly useful when a previous run
            # finished System A but was interrupted before
            # System B could be evaluated.
            #
            # The script checks whether the key exists; it does
            # not separately validate the completeness of the
            # saved system-specific result.
            if key in result["systems"]:
                continue

            # Send the summary and scenario reviews to the
            # OpenAI-based claim judge.
            #
            # prompt("claim_judge.txt") loads the evaluation
            # instructions, which define how the judge should
            # assess the summary.
            #
            # canonical() serializes the summary and reviews
            # into a consistent JSON string.
            #
            # Notice that the payload contains only:
            # - The summary generated by the selected system.
            # - The reviews supplied to that system.
            #
            # It does not contain attack labels, annotations,
            # or the genuine-review benchmark.
            #
            # This is a real API call and may incur usage costs.
            verdict, raw, rid, usage = openai_json(
                prompt("claim_judge.txt"),
                canonical(
                    {
                        "summary": item[key]["summary"],
                        "reviews": reviews,
                    }
                ),
            )

            # Store the judge's output and API metadata.
            #
            # audit contains the parsed JSON judgment.
            # raw_response preserves the original model output.
            # request_id identifies the API response.
            # usage records token consumption and related metadata.
            #
            # Preserving these fields supports later inspection
            # of questionable judgments and experimental costs.
            result["systems"][key] = {
                "audit": verdict,
                "raw_response": raw,
                "request_id": rid,
                "usage": usage,
            }

            # Save the audit immediately after each system finishes.
            #
            # This creates a checkpoint before moving to the
            # next system.
            #
            # If execution stops after System A is completed,
            # its result remains saved and can be reused when
            # the script is run again.
            #
            # write_json() creates the output directory if needed.
            write_json(out, result)

        # Both system entries have now been processed or were
        # already present in the resumed audit.
        #
        # Mark the scenario as complete.
        #
        # This status indicates that the expected system entries
        # exist; it does not independently verify the correctness
        # of the judge's conclusions.
        result["status"] = "complete"

        # Save the final audit record with its completed status.
        write_json(out, result)

        # Report the location of the saved audit.
        print("Saved", out)


# Execute the auditing workflow only when this file is run directly.
#
# Importing the script from another Python module does not
# automatically begin evaluating scenarios or making API calls.
if __name__ == "__main__":
    main()
